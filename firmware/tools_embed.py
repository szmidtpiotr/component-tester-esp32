"""Embed ui/index.html and ui/openapi.json (gzipped) into src/assets.h.

Runs automatically before every PlatformIO build (extra_scripts = pre:tools_embed.py)
and can also be run by hand: python3 tools_embed.py
"""
import gzip
import os
import pathlib

try:                                    # inside PlatformIO (SCons)
    Import("env")                       # noqa: F821
    root = pathlib.Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:                       # plain python
    root = pathlib.Path(os.path.dirname(os.path.abspath(__file__)))

out = ["// Generated by tools_embed.py from ui/ - do not edit.", "#pragma once", "#include <Arduino.h>"]
for name, path in [("INDEX_HTML", "ui/index.html"), ("OPENAPI_JSON", "ui/openapi.json")]:
    data = gzip.compress((root / path).read_bytes(), 9, mtime=0)
    out.append(f"static const uint8_t {name}_GZ[] PROGMEM = {{{','.join(str(b) for b in data)}}};")
    out.append(f"static const size_t {name}_GZ_LEN = {len(data)};")
(root / "src" / "assets.h").write_text("\n".join(out) + "\n")
print("tools_embed: src/assets.h updated")
